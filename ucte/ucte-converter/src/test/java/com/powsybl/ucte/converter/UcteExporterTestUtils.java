package com.powsybl.ucte.converter;

import com.powsybl.commons.datasource.MemDataSource;
import com.powsybl.commons.datasource.ReadOnlyMemDataSource;
import com.powsybl.iidm.network.Network;
import com.powsybl.iidm.network.NetworkFactory;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.Properties;

/**
 * Helpers shared by the UCTE exporter tests.
 *
 * @author Arthur Michaut {@literal <arthur.michaut at artelys.com>}
 */
final class UcteExporterTestUtils {

    private UcteExporterTestUtils() {
    }

    /**
     * Re-imports a network exported to a {@link MemDataSource}. A plain {@link MemDataSource} always stores its
     * content under an empty base name, which {@link UcteImporter} would otherwise turn into an invalid empty
     * network id, so the exported bytes are copied into a named {@link ReadOnlyMemDataSource} first.
     */
    static Network reimport(MemDataSource dataSource) {
        byte[] exported = dataSource.getData(null, "uct");
        ReadOnlyMemDataSource namedDataSource = new ReadOnlyMemDataSource("network");
        namedDataSource.putData("network.uct", exported);
        return new UcteImporter().importData(namedDataSource, NetworkFactory.findDefault(), null);
    }

    /**
     * Run the UCTE exporter and return its output as a {@link String}. Charset used for encoding is {@code UTF-8}
     *
     * @param ucteExporter an exporter to use for export
     * @param network      a network to export
     * @return UTF-8 encoded String containing the exported network
     * @throws UncheckedIOException if something goes wrong while trying to write the exported data
     */
    static String exportToString(UcteExporter ucteExporter, Network network) {
        return exportToString(ucteExporter, network, new Properties());
    }

    /**
     * Run the UCTE exporter with the given parameters and return its output as a {@link String}. Charset used for
     * encoding is {@code UTF-8}
     *
     * @param ucteExporter an exporter to use for export
     * @param network      a network to export
     * @param parameters   the export parameters
     * @return UTF-8 encoded String containing the exported network
     * @throws UncheckedIOException if something goes wrong while trying to write the exported data
     */
    static String exportToString(UcteExporter ucteExporter, Network network, Properties parameters) {
        MemDataSource dataSource = new MemDataSource();
        ucteExporter.export(network, parameters, dataSource);
        try (InputStream is = dataSource.newInputStream(null, "uct")) {
            // The export timestamp changes at each run
            return new String(is.readAllBytes(), StandardCharsets.UTF_8)
                    .replaceFirst("Generated by powsybl, .*", "Generated by powsybl, <export date>");
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
